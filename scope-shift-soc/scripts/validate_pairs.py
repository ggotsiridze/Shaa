"""Validate controlled pairs and (re)write PAIR_DIFF_REPORT.md."""

import json
import sys
from pathlib import Path

from _common import ROOT

from scopeshift.errors import TaskValidationError
from scopeshift.loader import load_pairs, load_tasks
from scopeshift.pair_validation import validate_all_pairs


def _fmt(v: object) -> str:
    s = json.dumps(v) if not isinstance(v, str) else v
    return s.replace("|", "\\|")


def main() -> int:
    task_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "tasks" / "development"
    report = ROOT / ("PAIR_DIFF_REPORT.md" if task_dir.name == "development" else f"PAIR_DIFF_REPORT_{task_dir.name}.md")
    try:
        tasks = load_tasks(task_dir)
        pairs = load_pairs(task_dir)
    except TaskValidationError as exc:
        print(f"FAIL: {exc}")
        return 1
    reports = validate_all_pairs(pairs, tasks)
    lines = ["# PAIR_DIFF_REPORT", "", "Generated by `python scripts/validate_pairs.py`. Do not edit by hand.", ""]
    for r in reports:
        print(f"{'OK  ' if r.ok else 'FAIL'} {r.pair_id}")
        for p in r.problems:
            print(f"     {p}")
        lines += [f"## {r.pair_id}: {'PASS' if r.ok else 'FAIL'}", ""]
        if r.pair_id in pairs:
            lines += [f"Purpose: {pairs[r.pair_id].get('purpose', '')}", "",
                      "Declared model-visible differences: " +
                      ", ".join(f"`{d}`" for d in pairs[r.pair_id].get("expected_model_visible_differences", [])), ""]
        lines += ["### Model-visible diff (A vs B)", "", "| path | A | B |", "|---|---|---|"]
        lines += [f"| `{k}` | {_fmt(a)} | {_fmt(b)} |" for k, (a, b) in r.visible_diff.items()]
        lines += ["", "### Hidden-field diff (expected to differ; not shown to the model)", ""]
        for k, (a, b) in r.hidden_diff.items():
            lines += [f"- `{k}`", f"  - A: `{json.dumps(a)}`", f"  - B: `{json.dumps(b)}`"]
        if r.problems:
            lines += ["", "### Problems", ""] + [f"- {p}" for p in r.problems]
        lines.append("")
    report.write_text("\n".join(lines), encoding="utf-8")
    ok = all(r.ok for r in reports)
    print(f"{len(reports)} pairs checked: {'PASS' if ok else 'FAIL'} (report: {report.name})")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
